# ============================================================================
# CNN 1
# ============================================================================

cnn1 = Chain(

    Conv((3,3), 1=>8, pad=(1,1), relu),
    MaxPool((2,2)),

    x -> reshape(x, :, size(x,4)),

    Dense(8192, 4),
    softmax
)

